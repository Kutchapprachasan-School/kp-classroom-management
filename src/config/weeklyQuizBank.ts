const pad2 = (n: number): string => String(n).padStart(2, '0');

/** คลังคำถามดั้งเดิมทั้ง 120 ข้อ (ยังไม่รวม override ของแอดมิน) */
export const WEEKLY_QUIZ_BANK: WeeklyQuizQuestion[] = SEEDS.flatMap((week, wi) =>
  week.map(([subject, question, choices, answerIndex, explanation], qi) => ({
    id: `w${pad2(wi + 1)}-q${qi + 1}`,
    week: wi + 1,
    subject,
    question,
    choices,
    answerIndex,
    explanation,
  }))
);

export const getBankQuestionsForWeek = (week: number): WeeklyQuizQuestion[] =>
  WEEKLY_QUIZ_BANK.filter((q) => q.week === week);

/** ภาคเรียนของสัปดาห์ที่ระบุ (1–20 = ภาค 1, 21–40 = ภาค 2) */
export const getTermForQuizWeek = (week: number): 1 | 2 => (week <= WEEKS_PER_TERM ? 1 : 2);
